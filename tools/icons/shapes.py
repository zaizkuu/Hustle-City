"""Tiny shape helpers that emit SVG path strings on the 24x24 icon grid, for icon generator scripts."""
import math


def f(v):
    s = f'{v:.2f}'.rstrip('0').rstrip('.')
    return s if s not in ('-0', '') else '0'


def circle(cx, cy, r):
    return f'M{f(cx - r)} {f(cy)}a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0z'


def ellipse(cx, cy, rx, ry):
    return f'M{f(cx - rx)} {f(cy)}a{f(rx)} {f(ry)} 0 1 0 {f(2 * rx)} 0a{f(rx)} {f(ry)} 0 1 0 {f(-2 * rx)} 0z'


def rect(x, y, w, h, r=0.0):
    if r <= 0:
        return f'M{f(x)} {f(y)}h{f(w)}v{f(h)}h{f(-w)}z'
    r = min(r, w / 2, h / 2)
    return (f'M{f(x + r)} {f(y)}h{f(w - 2 * r)}a{f(r)} {f(r)} 0 0 1 {f(r)} {f(r)}v{f(h - 2 * r)}'
            f'a{f(r)} {f(r)} 0 0 1 {f(-r)} {f(r)}h{f(-(w - 2 * r))}a{f(r)} {f(r)} 0 0 1 {f(-r)} {f(-r)}'
            f'v{f(-(h - 2 * r))}a{f(r)} {f(r)} 0 0 1 {f(r)} {f(-r)}z')


def poly(*pts):
    s = f'M{f(pts[0][0])} {f(pts[0][1])}'
    for x, y in pts[1:]:
        s += f'L{f(x)} {f(y)}'
    return s + 'z'


def line(*pts):
    s = f'M{f(pts[0][0])} {f(pts[0][1])}'
    for x, y in pts[1:]:
        s += f'L{f(x)} {f(y)}'
    return s


def star(cx, cy, r1, r2, n=5, rot=-90):
    pts = []
    for i in range(n * 2):
        r = r1 if i % 2 == 0 else r2
        a = math.radians(rot + i * 180 / n)
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return poly(*pts)


def sector(cx, cy, r, a0, a1):
    """Pie slice from angle a0 to a1 (degrees, 0 = east, clockwise on screen)."""
    x0, y0 = cx + r * math.cos(math.radians(a0)), cy + r * math.sin(math.radians(a0))
    x1, y1 = cx + r * math.cos(math.radians(a1)), cy + r * math.sin(math.radians(a1))
    large = 1 if (a1 - a0) % 360 > 180 else 0
    return f'M{f(cx)} {f(cy)}L{f(x0)} {f(y0)}A{f(r)} {f(r)} 0 {large} 1 {f(x1)} {f(y1)}z'


def L(d, color, alpha=None, stroke=None, evenodd=False):
    """One Kotlin L(...) layer; color like 'E5484D' (opaque) or 'AARRGGBB'."""
    c = color if len(color) == 8 else 'FF' + color
    s = f'L("{d}", 0x{c.upper()}'
    if alpha is not None:
        s += f', alpha = {f(alpha)}f'
    if stroke is not None:
        s += f', stroke = {f(stroke)}f'
    if evenodd:
        s += ', evenOdd = true'
    return s + ')'


def icon(iid, *layers):
    body = ',\n            '.join(layers)
    return f'        icon("{iid}",\n            {body},\n        ),'


def kotlin_file(obj, doc, icons):
    return ('package com.hustlecity.game.ui.icons\n\n'
            f'/** {doc} Generated by tools/icons/{obj.lower()}.py — edit the script, not this file. */\n'
            f'object {obj} : IconSet {{\n    override val icons = listOf(\n' + '\n'.join(icons) + '\n    )\n}\n')
